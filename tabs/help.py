from __future__ import annotations
import streamlit as st

def render_help_tab():
    st.subheader("Справка по калькулятору фьючерсов")
    st.markdown("В этом разделе собрана информация о работе с приложением. Раскройте интересующий пункт, чтобы узнать подробности.")

    with st.expander("1. Навигация и общее описание"):
        st.markdown("""
        Приложение состоит из трех основных рабочих вкладок:
        *   **Данные** — здесь вы выбираете инструменты (тикеры), которые хотите отслеживать. Для выбранных инструментов строится таблица с рыночными данными, гарантийным обеспечением и параметрами для анализа.
        *   **Скринер** — инструмент для поиска наиболее ликвидных и подходящих по депозиту контрактов среди всех доступных на бирже MOEX.
        *   **Калькуляторы фьючерсов** — главный рабочий раздел. Здесь для каждого выбранного тикера создается отдельный калькулятор, в котором можно строить графики, размечать тренды и рассчитывать параметры сделки.

        **Боковое меню** содержит глобальные настройки, которые применяются ко всем калькуляторам сразу (размер депозита, допустимый риск, комиссия и т.д.).
        """)

    with st.expander("2. Настройки в боковом меню"):
        st.markdown("""
        *   **Профиль данных** — позволяет создавать независимые сохранения. Если вы хотите вести разные стратегии, создайте новый профиль.
        *   **Стратегия** — влияет на то, как строятся зоны RR (риск/прибыль) на графиках. В режиме «Зигзаг тенденции» зоны строятся по последнему движению, в «Свинг торговля» — по всему движению.
        *   **Депозит** — сумма средств на вашем счете. От этого значения рассчитывается доступное количество контрактов и сумма риска.
        *   **Допустимый риск в сделке** — процент от депозита, которым вы готовы рискнуть в одной сделке. По умолчанию 1%. Калькулятор не даст вам взять больше контрактов, чем позволяет этот лимит.
        *   **Risk/Reward (1 к ...)** — ваше целевое соотношение прибыли к риску. Если вы рискуете 1000 рублей, а хотите заработать 3000, это соотношение 1 к 3. Калькулятор предупредит, если фактическая сделка не дотягивает до этого значения.
        *   **Категория риска** — ваш статус клиента на бирже (КНУР, КСУР, КПУР и т.д.). От этого зависит размер гарантийного обеспечения (ГО), которое биржа заморозит под вашу сделку. Чем выше категория, тем меньше ГО.
        """)

    with st.expander("3. Вкладка «Данные»"):
        st.markdown("""
        *   **Выбор инструментов** — начните вводить тикер в поле «Выбрать из списка», чтобы найти нужный контракт. Если вы хотите добавить контракт, которого нет в списке (например, дальний фьючерс), впишите его тикер вручную в поле справа.
        *   **Удаление тикера** — нажмите на крестик рядом с тикером в поле выбора, чтобы убрать его из списка. Калькулятор для этого тикера также будет удален.
        *   **Таблица рыночных данных** — отображает текущую цену, открытый интерес (ликвидность), дату экспирации и гарантийное обеспечение (ГО) на покупку и продажу с учетом вашей категории риска.
        *   **Доступно контрактов** — сколько контрактов вы можете купить на свой депозит, исходя из размера ГО.
        *   **Настройка тренда** — в раскрывающемся блоке можно указать текущее состояние рынка (Тренд, Волна, Тенденция). Эти данные используются в калькуляторе для автоматической подсказки направления сделки.
        """)

    with st.expander("4. Вкладка «Скринер»"):
        st.markdown("""
        Скринер помогает отфильтровать весь список фьючерсов MOEX по важным для вас параметрам.
        *   **Ликвидность** — вы можете отобрать контракты с высоким объемом торгов или открытым интересом.
        *   **ГО и депозит** — установите галочку «Помещающиеся в депо», и скринер скроет контракты, на которые вам не хватит денег.
        *   **Только ближайшие** — оставляет только самые ближние к экспирации контракты (фронт-месяцы), убирая дальние серии.
        *   **Зеленая подсветка** — выделяет самый торгуемый контракт для каждого базового актива (например, самый активный фьючерс на индекс RTS).
        """)

    with st.expander("5. Вкладка «Калькуляторы фьючерсов»: Графики и разметка"):
        st.markdown("""
        В верхней части калькулятора находится блок графиков, разделенный на таймфреймы (D1, H1, M10, M1).
        *   **Инструмент (Канал)** — доступен только на дневном графике (D1). Чтобы построить канал, кликните на первый бар (задав начало тренда), затем на второй бар (задав конец тренда). Программа автоматически найдет наивысшую (или наинизшую) точку между ними и построит ровные параллельные линии.
        *   **Инструмент (Зигзаг)** — доступен на H1, M10 и M1. Кликайте по графикам, чтобы расставить точки. Первая точка — начало, вторая — конец. Если вы кликаете в ту же свечу, направление точки меняется (с минимума на максимум и наоборот).
        *   **Инструмент (Уровень 1/2)** — строит горизонтальную линию ровно посередине между двумя выбранными вами точками (уровень 50%).
        *   **Кнопки «Отменить» и «Очистить»** — позволяют удалить последнюю поставленную точку или стереть всю разметку целиком.
        *   **Панель объемов** — внизу графика отображаются объемы торгов. Аномально высокие объемы подсвечиваются цветом (зеленым на H1, красным на минутных ТФ, синим на D1), что помогает найти важные уровни.
        """)

    with st.expander("6. Анализ пробоев и откатов (на H1)"):
        st.markdown("""
        Как только вы расставите минимум 4 точки зигзага на часовом таймфрейме (H1), калькулятор автоматически проанализирует структуру рынка.
        *   **Пробой** — это движение в сторону тренда (обновление максимума для роста или минимума для падения). Калькулятор оценивает силу пробоя: сравнивает его высоту, количество затраченных баров и объем с предыдущим пробоем.
        *   **Откат** — это движение против тренда. Калькулятор оценивает его глубину относительно уровня 50% (0.5 Фибоначчи) от предыдущего движения.
            *   Если откат **не доходит до середины** (0.5 Fib) — он считается **слабым**. Это признак **сильного тренда**, так как продавец (или покупатель) не смог увести цену глубоко. На плашке и в таблице такой откат подсвечивается **зеленым** цветом.
            *   Если откат **падает за середину** (0.5 Fib) — он считается **сильным (глубоким)**. Это признак **слабости тренда**. На плашке и в таблице он подсвечивается **красным** цветом.
        *   **Зоны RR (Риск/Прибыль)** — автоматически отображаются на графике в виде цветных прямоугольников, опираясь на последний найденный пробой.
        """)

    with st.expander("7. Кластеры объемов (M10)"):
        st.markdown("""
        Кластеры объемов — это горизонтальные зоны (оранжевого цвета), которые показывают скопление значимых объемов.
        *   Чтобы включить их отображение, активируйте переключатель «Кластеры объемов (M10)» под блоком параметров сделки.
        *   **Как строятся:** Анализируются только бары с аномальным объемом на таймфрейме M10. От каждого такого бара строится зона вправо до конца графика (от Close до High для продаж, и от Low до Close для покупок).
        *   **Наложение:** Там, где зоны разных баров накладываются друг на друга, яркость заливки увеличивается (эффект слоев). Это указывает на самые важные ценовые уровни (POC).
        *   **Порог отсечения:** Слайдер под переключателем позволяет отсечь зоны с маленьким суммарным объемом. Значение `10` покажет все зоны, а `100` оставит только область с максимальным объемом.
        """)

    with st.expander("8. Параметры сделки и расчет позиции"):
        st.markdown("""
        В нижней части калькулятора находится блок для расчета вашей будущей сделки.
        *   **Направление** — выберите LONG (покупка) или SHORT (продажа).
        *   **Точки входа (ТВХ)** — таблица окрашена в **синий** цвет. Вы можете добавить одну или несколько точек входа (например, если планируете усредняться). Введите цену и количество контрактов.
        *   **Стоп-лосс (SL)** — поле ввода окрашено в **красный** цвет. Это цена, при которой сделка закроется с убытком. Для покупки стоп должен быть ниже входа, для продажи — выше.
        *   **Тейк-профит (TP)** — поле ввода окрашено в **зеленый** цвет. Это цена, при которой вы зафиксируете прибыль.
        *   **Минимальный TP и Целевая прибыль** — калькулятор автоматически рассчитывает, каким должен быть TP, чтобы окупить комиссии за вход и выход, и получить прибыль в заданном размере (Risk/Reward). Если оставить поле TP пустым (0), система сама подставит этот минимально необходимый уровень.
        *   **Результаты расчета** — калькулятор автоматически посчитает стоимость позиции, плечо, размер гарантийного обеспечения (ГО), комиссию и чистый финансовый результат (в рублях) с учетом вашего допустимого риска. Если риск превышен, вы увидите красное предупреждение.
        """)

    with st.expander("9. Экспорт и импорт JSON (сохранение сессии)"):
        st.markdown("""
        Все ваши настройки, нарисованные линии, точки зигзагов и параметры сделок хранятся в оперативной памяти. Чтобы не потерять их при обновлении страницы или при переходе на другое устройство, используйте функцию экспорта.
        
        **Как сохранить (Экспорт):**
        1. В боковом меню нажмите кнопку «Экспорт сессии».
        2. У вас скачается файл с расширением `.futures` (это текстовый файл в формате JSON).
        3. Сохраните его на компьютер.

        **Как загрузить (Импорт):**
        1. Если вы хотите продолжить работу, в боковом меню найдите блок «Управление настройками» и нажмите «Импорт».
        2. Выберите ранее скачанный файл `.futures`.
        3. Нажмите «Применить импорт». Приложение перезагрузится, и все ваши вкладки, калькуляторы и нарисованные графики вернутся на свои места.
        
        **Важно:** Импорт полностью заменяет текущую сессию данными из файла. Если вы нарисовали новые линии, но не сохранили их в файл, они будут утеряны при импорте старого файла.
        """)
